"""Generate `accuracy-vectors.json`: `weapons.shot_cone`, pinned three ways.

    PYTHONPATH=. uv run python scripts/gen_hassault_accuracy_vectors.py

The server fires every shot through `shot_cone`. The browser and native training
ranges evaluate it too (`trace.ts`, `trace.rs`), and a range that taught a
different cone from a match would teach the wrong thing about stopping to shoot.
The fixture carries the served weapon table, so the cases index into one copy of
the numbers, and a `weaponsSpecId` content hash of that table, so a balance
change without a regeneration fails loudly (`test_hassault_accuracy.py`) instead
of leaving the clients pinned against yesterday's guns. A separate file from
`physics-vectors.json` on purpose: tuning a gun must not churn the movement
fixture.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

from backend.modules.hassault import weapons
from backend.modules.hassault.physics import MOVE_SPEED

OUT = Path("packages/core/src/modules/hassault/__tests__/accuracy-vectors.json")


def weapons_spec_id() -> str:
    """A content hash of the served weapon table."""
    table = [w.to_dict() for w in weapons.WEAPONS]
    blob = json.dumps(table, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()[:16]


#: Each context, named for the claim it makes.
CONTEXTS: list[tuple[str, dict[str, Any]]] = [
    ("standing, first shot", {}),
    ("standing, straight after a shot", {"since_last_shot": 0.05}),
    ("standing, half recovered", {"since_last_shot": 0.15}),
    ("walking", {"speed": MOVE_SPEED * 0.52}),
    ("at the accurate threshold", {"speed": MOVE_SPEED * weapons.ACCURATE_SPEED_SCALE}),
    ("running", {"speed": MOVE_SPEED}),
    ("faster than a run", {"speed": MOVE_SPEED * 1.25}),
    ("airborne", {"airborne": True, "speed": MOVE_SPEED}),
    ("crouched", {"crouch": 1.0}),
    ("half crouched, running", {"crouch": 0.5, "speed": MOVE_SPEED}),
    ("scoped", {"scoped": 1}),
    ("scoped, running", {"scoped": 2, "speed": MOVE_SPEED}),
]


def _cases() -> list[dict[str, Any]]:
    out = []
    for weapon in weapons.WEAPONS:
        for name, ctx in CONTEXTS:
            shot = weapons.ShotContext(**ctx)
            out.append(
                {
                    "name": f"{weapon.id}: {name}",
                    "weapon": weapon.id,
                    "ctx": {
                        "speed": shot.speed,
                        "airborne": shot.airborne,
                        "crouch": shot.crouch,
                        "scoped": shot.scoped,
                        "sinceLastShot": shot.since_last_shot,
                    },
                    "expect": weapons.shot_cone(weapon, shot),
                }
            )
    return out


def payload() -> dict[str, Any]:
    return {
        "_comment": (
            "Generated by scripts/gen_hassault_accuracy_vectors.py from "
            "weapons.shot_cone. Do not edit by hand."
        ),
        "weaponsSpecId": weapons_spec_id(),
        "moveSpeed": MOVE_SPEED,
        "accurateSpeedScale": weapons.ACCURATE_SPEED_SCALE,
        "tolerance": 1e-9,
        "weapons": {w.id: w.to_dict() for w in weapons.WEAPONS},
        "cases": _cases(),
    }


def main() -> None:
    OUT.write_text(json.dumps(payload(), indent=2) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
