/**
 * The radar's arithmetic, and the fixture the native radar replays.
 *
 * `radar-vectors.json` is the browser's own output from `radar-view.ts`, read by
 * `apps/native-fps/src/radar.rs`'s conformance module and by
 * `backend/tests/test_hassault_radar_heard.py` (for the own-noise radii, which
 * copy `noise.py`). Generated here, from the real module, for the reason
 * `surface-conformance.test.ts` gives: a generator with its own copy of the
 * maths would pin the copy. To rewrite it after a deliberate change:
 *
 *     UPDATE_RADAR_VECTORS=1 pnpm --filter @horrible/core test radar-view
 *
 * then change the native client in the same commit until both suites pass.
 */
import { readFileSync, writeFileSync } from 'node:fs';

import { describe, expect, it } from 'vitest';

