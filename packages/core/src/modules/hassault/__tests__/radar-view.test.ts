const PROJECT_POINTS: [number, number][] = [
  [50, 60],
  [60, 60],
  [50, 40],
  [0, 0],
  [200, 31],
];

const READ_CASES: Record<string, unknown>[] = [
  {},
  { 'hassault.radar.scale': 0.1, 'hassault.radar.hudScale': 9, 'hassault.radar.iconScale': -1 },
  {
    'hassault.radar.scale': '0.45',
    'hassault.radar.rotate': false,
    'hassault.radar.centered': 'yes',
  },
  {
    'hassault.radar.scale': null,
    'hassault.radar.soundPings': false,
    'hassault.radar.fullOnScores': false,
  },
];

function compute() {
  const frames = FRAME_CASES.map((c) => {
    const settings = { ...RADAR_DEFAULTS, ...c.settings };
    const frame = radarFrame(settings, c.me, c.ssize, c.scores, c.zoom);
    return {
      name: c.name,
      settings,
      me: c.me,
      ssize: c.ssize,
      scores: c.scores,
      zoom: c.zoom,
      frame,
      // At radius 1, so the numbers are the fractions both clients scale up.
      projected: PROJECT_POINTS.map(([x, y]) => ({ x, y, at: project(frame, 1, x, y) })),
    };
  });
  const kinds: BlipKind[] = ['mate', 'enemy', 'heard', 'lastKnown', 'ping', 'bomb', 'you'];
  const blips = [0.4, 0.6, 1].flatMap((iconScale) =>
    kinds.map((kind) => ({ kind, iconScale, radius: blipRadius(kind, iconScale) })),
  );
  const bands = [
    [0, 0, 10],
    [10, 0, 10],
    [5, 0, 10],
    [3, 0, 10],
    [-4, -4, 12],
    [7, 7, 7],
  ].map(([floor, lo, hi]) => ({ floor, lo, hi, band: floorBand(floor, lo, hi) }));
  const floorColors = Array.from({ length: FLOOR_BANDS }, (_, band) => ({
    band,
    rgba: floorColor(band),
  }));
  const reads = READ_CASES.map((bag) => ({
    bag,
    settings: readRadarSettings((key) => bag[key]),
  }));
  return {
    why: 'Generated by radar-view.test.ts with UPDATE_RADAR_VECTORS=1 - do not hand-edit.',
    constants: {
      baseSpan: BASE_SPAN,
      defaultScale: DEFAULT_SCALE,
      zoomScale: ZOOM_SCALE,
      defaultIconScale: DEFAULT_ICON_SCALE,
      floorBands: FLOOR_BANDS,
      heardSeconds: HEARD_SECONDS,
    },
    defaults: RADAR_DEFAULTS,
    reads,
    frames,
    blips,
    bands,
    floorColors,
    colors: RADAR_COLORS,
    edges: { grid: GRID, edges: wallEdges(GRID.length, gridSolid) },
    noise: {
      ownRadii: OWN_NOISE_RADII,
      shots: [0, 10, 25, 40, 60, 100, 200].map((damage) => ({
        damage,
        radius: shotRadius(damage, false),
      })),
      knife: shotRadius(50, true),
    },
  };
}

type Vectors = ReturnType<typeof compute>;

const path = new URL('./radar-vectors.json', import.meta.url);

if (process.env.UPDATE_RADAR_VECTORS) {
  writeFileSync(path, `${JSON.stringify(compute(), null, 2)}\n`);
}

const vectors = JSON.parse(readFileSync(path, 'utf-8')) as Vectors;

describe('radar vectors', () => {
  it('match what radar-view.ts computes today', () => {
    // The fixture is the browser's output; if this fails, either regenerate on
    // purpose (and fix the native side) or the browser drifted by accident.
    expect(JSON.parse(JSON.stringify(compute()))).toEqual(vectors);
  });
});

describe('radar frame', () => {
  const base = { ...RADAR_DEFAULTS };

  it('keeps the old 110-cube span at the default zoom', () => {
    expect(radarFrame(base, { x: 0, y: 0, yaw: 0 }, 256, false, false).span).toBe(110);
  });

  it('shows more map at a lower scale, the way cl_radar_scale does', () => {
    const wide = radarFrame({ ...base, scale: 0.4 }, { x: 0, y: 0, yaw: 0 }, 256, false, false);
    expect(wide.span).toBeCloseTo(192.5, 6);
  });

  it('puts what is ahead at the top when rotating', () => {
    for (const yaw of [0, 1, -2.4, Math.PI]) {
      const me = { x: 100, y: 100, yaw };
      const frame = radarFrame(base, me, 256, false, false);
      const [x, y] = project(frame, 1, me.x + Math.cos(yaw) * 10, me.y + Math.sin(yaw) * 10);
      expect(x).toBeCloseTo(0, 9);
      expect(y).toBeLessThan(0);
    }
  });

  it('puts what is on our right on the right', () => {
    // y-down world: right of facing +x is +y.
    const me = { x: 100, y: 100, yaw: 0 };
    const [x] = project(radarFrame(base, me, 256, false, false), 1, 100, 110);
    expect(x).toBeGreaterThan(0);
  });

  it('north-up keeps the world still and turns the arrow', () => {
    const a = radarFrame({ ...base, rotate: false }, { x: 50, y: 50, yaw: 0 }, 256, false, false);
    const b = radarFrame({ ...base, rotate: false }, { x: 50, y: 50, yaw: 1 }, 256, false, false);
    expect(a.angle).toBe(0);
    expect(b.angle).toBe(0);
    expect(b.arrowAngle - a.arrowAngle).toBeCloseTo(1, 9);
  });

  it('stops at the map edge when not centred', () => {
    const f = radarFrame({ ...base, centered: false }, { x: 3, y: 250, yaw: 0 }, 256, false, false);
    expect(f.cx).toBeCloseTo(55, 9);
    expect(f.cy).toBeCloseTo(201, 9);
  });

  it('holding zoom never zooms in a radar already wider than it', () => {
    const f = radarFrame({ ...base, scale: 0.3 }, { x: 0, y: 0, yaw: 0 }, 256, false, true);
    expect(f.span).toBeCloseTo((110 * 0.7) / 0.3, 9);
  });

  it('fits the whole map, corners included, while the scoreboard is held', () => {
    const f = radarFrame(base, { x: 10, y: 10, yaw: 0 }, 128, true, false);
    const [x, y] = project(f, 1, 0, 0);
    expect(Math.hypot(x, y)).toBeLessThanOrEqual(1 + 1e-9);
  });
});

describe('wall edges', () => {
  const edges = wallEdges(GRID.length, gridSolid);

  it('outlines every open cell side that touches a wall, exactly once', () => {
    const covered = new Map<string, number>();
    for (const e of edges) {
      if (e.y0 === e.y1) {
        for (let x = e.x0; x < e.x1; x += 1) {
          const k = `h${x},${e.y0}`;
          covered.set(k, (covered.get(k) ?? 0) + 1);
        }
      } else {
        for (let y = e.y0; y < e.y1; y += 1) {
          const k = `v${e.x0},${y}`;
          covered.set(k, (covered.get(k) ?? 0) + 1);
        }
      }
    }
    const n = GRID.length;
    const open = (x: number, y: number) => x >= 0 && y >= 0 && x < n && y < n && !gridSolid(x, y);
    let expected = 0;
    for (let y = 0; y <= n; y += 1)
      for (let x = 0; x < n; x += 1)
        if (open(x, y - 1) !== open(x, y)) {
          expected += 1;
          expect(covered.get(`h${x},${y}`), `h${x},${y}`).toBe(1);
        }
    for (let x = 0; x <= n; x += 1)
      for (let y = 0; y < n; y += 1)
        if (open(x - 1, y) !== open(x, y)) {
          expected += 1;
          expect(covered.get(`v${x},${y}`), `v${x},${y}`).toBe(1);
        }
    expect([...covered.values()].reduce((a, b) => a + b, 0)).toBe(expected);
  });

  it('closes a corridor that runs out to the edge of the grid', () => {
    // Row 6 is open to x = 9, the grid's last column: outside counts as solid.
    expect(edges.some((e) => e.x0 === 10 && e.x1 === 10 && e.y0 <= 6 && e.y1 > 6)).toBe(true);
  });

  it('merges straight runs rather than emitting one segment per cell', () => {
    expect(edges.some((e) => e.x1 - e.x0 > 1 || e.y1 - e.y0 > 1)).toBe(true);
  });
});

describe('settings', () => {
  it('clamps to the schema and falls back on garbage', () => {
    const s = readRadarSettings((k) => READ_CASES[1][k]);
    expect(s.scale).toBe(0.3);
    expect(s.hudScale).toBe(1.3);
    expect(s.iconScale).toBe(0.4);
    const t = readRadarSettings((k) => READ_CASES[2][k]);
    expect(t.scale).toBeCloseTo(0.45, 9);
    expect(t.rotate).toBe(false);
    expect(t.centered).toBe(true);
  });

  it('draws blips the size they always were at the default icon scale', () => {
    expect(blipRadius('mate', 0.6) * 84).toBeCloseTo(3.2, 9);
    expect(blipRadius('enemy', 0.6) * 84).toBeCloseTo(3.8, 9);
    expect(blipRadius('enemy', 0.6)).toBeGreaterThan(blipRadius('mate', 0.6));
  });
});
