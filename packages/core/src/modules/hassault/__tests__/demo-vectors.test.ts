/**
 * The `.hademo` format, pinned between the two clients.
 *
 * `demo-vectors.json` holds a demo as a file might arrive — numeric ids, an
 * optional field missing here and there, a header shorter than its frames —
 * then what `parseDemo` makes of it and what `DemoPlayer.sampleCurrentFrame`
 * draws at a handful of times, including either side of a scope step and
 * across the yaw seam. `apps/native-fps/src/demo.rs` parses the same file and
 * must agree. To rewrite it after a deliberate change:
 *
 *     UPDATE_DEMO_VECTORS=1 pnpm --filter @horrible/core test demo-vectors
 *
 * then change the native client in the same commit until both suites pass.
 *
 * Every number in the file is exactly representable in single precision, so
 * the native side's `f32` fields round-trip it without a tolerance.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { afterEach, describe, expect, it, vi } from 'vitest';

import { DemoPlayer, DemoRecorder, parseDemo } from '../demo';

const TAU = Math.PI * 2;

const body = (
  id: number | string,
  x: number,
  yaw: number,
  extra: Record<string, unknown> = {},
) => ({
  id,
  name: `p${id}`,
  team: Number(id) % 2,
  x,
  y: 2,
  z: 0.5,
  yaw,
  pitch: -0.25,
  weapon: 2,
  hp: 100,
  ...extra,
});

/** As a file might arrive: ids as numbers, a short header, fields absent. */
const FILE = {
  header: {
    magic: 'HADEMO',
    version: 1,
    map: 'hd_dust2',
    recordedAt: 1793227697703,
    tickRate: 30,
    playerNames: { '7': 'Sable', '8': 'Meridian' },
    durationMs: 0,
    pov: 7,
  },
  frames: [
    {
      tick: 0,
      timestamp: 0,
      players: [
        body(7, 0, TAU - 0.125, { weaponId: 'sniper', scoped: 0, zoom: 1, crouch: 0, alive: true }),
        body(8, 10, 1.5),
      ],
      events: [],
    },
    {
      tick: 1,
      timestamp: 32,
      players: [
        body(7, 1, 0.125, { weaponId: 'sniper', scoped: 1, zoom: 4, crouch: 0.5, alive: true }),
        body(8, 9, 1.5, { hp: 25 }),
      ],
      events: [{ tick: 1, timestamp: 20, type: 'kill', killerId: 7, victimId: 9, head: true }],
    },
    {
      tick: 2,
      timestamp: 64,
      // Player 8 has left: playback keeps whoever is in the earlier frame.
      players: [
        body(7, 3, 0.25, { weaponId: 'sniper', scoped: 1, zoom: 4, crouch: 1, alive: true }),
      ],
    },
  ],
  bookmarks: [{ tick: 1, timestamp: 20, label: 'HEADSHOT', type: 'headshot', targetPlayerId: '7' }],
};

const TIMES = [-10, 0, 8, 16, 24, 40, 48, 64, 100];

function compute() {
  const parsed = parseDemo(JSON.stringify(FILE));
  const player = new DemoPlayer();
  player.load(parsed);
  const samples = TIMES.map((t) => {
    player.seek(t);
    const { players, events } = player.sampleCurrentFrame();
    return { t, players, events };
  });
  return {
    why: 'Generated by demo-vectors.test.ts with UPDATE_DEMO_VECTORS=1 - do not hand-edit.',
    file: FILE,
    parsed,
    spectating: player.spectatorTargetId,
    samples,
  };
}

const path = new URL('./demo-vectors.json', import.meta.url);

if (process.env.UPDATE_DEMO_VECTORS) {
  writeFileSync(path, `${JSON.stringify(compute())}\n`);
}

describe('demo vectors', () => {
  it('match what demo.ts parses and samples today', () => {
    const vectors = JSON.parse(readFileSync(path, 'utf-8')) as ReturnType<typeof compute>;
    expect(JSON.parse(JSON.stringify(compute()))).toEqual(vectors);
  });
});

describe('the recorder', () => {
  afterEach(() => vi.restoreAllMocks());

  it('keeps thirty frames a second at 250 fps, not twenty-eight', () => {
    let now = 1000;
    vi.spyOn(performance, 'now').mockImplementation(() => now);
    const rec = new DemoRecorder();
    rec.start('hd_dust2', {}, 'you');
    for (; now < 2000; now += 4) {
      if (rec.due()) rec.recordFrame([]);
    }
    const demo = rec.stop();
    expect(demo?.frames.length).toBeGreaterThanOrEqual(29);
    expect(demo?.frames.length).toBeLessThanOrEqual(31);
  });
});
