/**
 * Planted feet and a true aim: the two things the operator got wrong.
 *
 * Players looked like they were skating because they were — the clips' feet
 * covered a fifth of the ground the body did — and a moving player's rifle
 * pointed across their chest rather than where they were looking. Both are
 * stated here as measurements on the shipped rigs, not as properties of the
 * code that fixes them: how far a foot on the ground moves, and how many
 * degrees the barrel and the face are off the look direction.
 *
 * `locomotion-vectors.json` is this side's own output from `locomotion.ts`,
 * replayed by `apps/native-fps/src/locomotion.rs`. To rewrite it after a
 * deliberate change:
 *
 *     UPDATE_LOCOMOTION_VECTORS=1 pnpm --filter @horrible/core test locomotion
 *
 * then change the native client in the same commit until both suites pass.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import * as THREE from 'three';
import { describe, expect, it } from 'vitest';

import { avatarRotationY } from '../avatars';
import { CharacterAnimator } from '../models/CharacterAnimator';
import { CharacterModel } from '../models/CharacterModel';
import { IDLE_SPEED } from '../models/clips';
import {
  createGait,
  DUTY_MAX,
  RUN_SPEED,
  stepGait,
  TELEPORT_SPEED,
  type GaitInput,
  type GaitOutput,
} from '../models/locomotion';
import type { PlayerRow } from '../net';
import { loadOperatorGlb } from './operator-glb';

const DT = 1 / 60;
/** Roughly the shipped rigs' proportions, for the cases that need no rig. */
const BODY = { hipHeight: 2.45, legLength: 2.55, hipWidth: 0.55 };

interface Frame {
  dt: number;
  x: number;
  y: number;
  yaw: number;
  alive: boolean;
  grounded: boolean;
}

/** A body driven at a velocity that changes on a schedule. */
function drive(
  legs: {
    until: number;
    vx: number;
    vy: number;
    yaw?: number;
    grounded?: boolean;
    jump?: number;
  }[],
  dt: (frame: number) => number = () => DT,
): Frame[] {
  const frames: Frame[] = [];
  let x = 40;
  let y = 37.5;
  let yaw = 0.4;
  let t = 0;
  let n = 0;
  for (const leg of legs) {
    if (leg.jump) x += leg.jump;
    while (t < leg.until) {
      const step = dt(n);
      x += leg.vx * step;
      y += leg.vy * step;
      yaw = leg.yaw ?? yaw;
      t += step;
      n += 1;
      frames.push({ dt: step, x, y, yaw, alive: true, grounded: leg.grounded ?? true });
    }
  }
  return frames;
}

const SCENARIOS: { name: string; frames: Frame[] }[] = [
  {
    name: 'run forward, stop, strafe, back up',
    frames: drive([
      { until: 0.2, vx: 0, vy: 0 },
      { until: 1.2, vx: 18 * Math.cos(0.4), vy: 18 * Math.sin(0.4) },
      { until: 1.6, vx: 0, vy: 0 },
      { until: 2.4, vx: -9 * Math.sin(0.4), vy: 9 * Math.cos(0.4) },
      { until: 3.0, vx: -6 * Math.cos(0.4), vy: -6 * Math.sin(0.4) },
    ]),
  },
  {
    name: 'diagonals with a turning look, uneven frames',
    frames: drive(
      [
        { until: 0.8, vx: 12, vy: 12, yaw: 0.2 },
        { until: 1.5, vx: 12, vy: -12, yaw: 1.3 },
        { until: 2.2, vx: -4, vy: 3, yaw: -2.6 },
      ],
      (n) => [1 / 144, 1 / 60, 1 / 30, 1 / 90][n % 4],
    ),
  },
  {
    name: 'a jump and a respawn',
    frames: drive([
      { until: 0.5, vx: 18, vy: 0 },
      { until: 0.9, vx: 18, vy: 0, grounded: false },
      { until: 1.3, vx: 18, vy: 0 },
      { until: 1.6, vx: 0, vy: 0, jump: 120 },
      { until: 2.0, vx: 0, vy: 5 },
    ]),
  },
];

function replay(frames: Frame[]): GaitOutput[] {
  const gait = createGait();
  return frames.map((f) => stepGait(gait, { ...f, ...BODY }, f.dt));
}

function compute() {
  return {
    why: 'Generated by locomotion.test.ts with UPDATE_LOCOMOTION_VECTORS=1 - do not hand-edit.',
    body: BODY,
    scenarios: SCENARIOS.map(({ name, frames }) => ({ name, frames, out: replay(frames) })),
  };
}

const path = new URL('./locomotion-vectors.json', import.meta.url);

if (process.env.UPDATE_LOCOMOTION_VECTORS) {
  writeFileSync(path, `${JSON.stringify(compute())}\n`);
}

describe('locomotion vectors', () => {
  it('match what locomotion.ts computes today', () => {
    const vectors = JSON.parse(readFileSync(path, 'utf-8')) as ReturnType<typeof compute>;
    expect(JSON.parse(JSON.stringify(compute()))).toEqual(vectors);
  });
});

/** Run a body at a constant velocity and return every frame's output. */
function cruise(vx: number, vy: number, seconds: number, yaw = 0): GaitOutput[] {
  const gait = createGait();
  const input: GaitInput = { x: 0, y: 0, yaw, alive: true, grounded: true, ...BODY };
  const out: GaitOutput[] = [];
  for (let t = 0; t < seconds; t += DT) {
    input.x += vx * DT;
    input.y += vy * DT;
    out.push(stepGait(gait, input, DT));
  }
  return out;
}

describe('gait', () => {
  it('leaves a standing body to its clip', () => {
    const out = cruise(0, 0, 1);
    expect(out.at(-1)!.weight).toBe(0);
    // Interpolation wobble under the idle floor must not start a stride.
    const wobble = cruise(IDLE_SPEED * 0.5, 0, 1);
    expect(wobble.at(-1)!.weight).toBe(0);
  });

  it.each([
    ['walking', 4],
    ['at a jog', 9],
    ['running', RUN_SPEED],
  ])('never moves a foot that is on the ground, %s', (_name, speed) => {
    for (let dir = 0; dir < 8; dir += 1) {
      const angle = (dir * Math.PI) / 4;
      const out = cruise(speed * Math.cos(angle), speed * Math.sin(angle), 3);
      let slid = 0;
      let grounded = 0;
      // Past the first stride, which starts from a standstill.
      for (let i = 60; i < out.length; i += 1) {
        for (let f = 0; f < 2; f += 1) {
          const now = out[i].feet[f];
          const before = out[i - 1].feet[f];
          if (now.lift === 0 && before.lift === 0) {
            grounded += 1;
            slid += Math.hypot(now.x - before.x, now.y - before.y);
          }
        }
      }
      expect(grounded, `direction ${dir}: no foot ever lands`).toBeGreaterThan(20);
      expect(slid, `direction ${dir}`).toBeLessThan(1e-9);
    }
  });

  it('keeps a planted foot within reach of its hip', () => {
    const gait = createGait();
    const input: GaitInput = { x: 0, y: 0, yaw: 0, alive: true, grounded: true, ...BODY };
    for (let i = 0; i < 400; i += 1) {
      // A run that reverses and turns hard, which is what tears legs off.
      const angle = Math.floor(i / 40) * 2.2;
      input.x += RUN_SPEED * Math.cos(angle) * DT;
      input.y += RUN_SPEED * Math.sin(angle) * DT;
      input.yaw = angle;
      const out = stepGait(gait, input, DT);
      for (let f = 0; f < 2; f += 1) {
        if (out.feet[f].lift !== 0) continue;
        const away = Math.hypot(out.feet[f].x - input.x, out.feet[f].y - input.y);
        const height = BODY.hipHeight - out.drop;
        expect(Math.hypot(away - BODY.hipWidth / 2, height)).toBeLessThan(BODY.legLength);
      }
    }
  });

  it('creeps with a foot always down and runs with both in the air', () => {
    const airborne = (out: GaitOutput[]) =>
      out.slice(60).filter((o) => o.feet[0].lift > 0 && o.feet[1].lift > 0).length;
    expect(airborne(cruise(3, 0, 3))).toBe(0);
    expect(airborne(cruise(RUN_SPEED, 0, 3))).toBeGreaterThan(0);
    expect(DUTY_MAX).toBeGreaterThan(0.5);
  });

  it('squares the pelvis on the axes and turns it into a diagonal', () => {
    const settled = (vx: number, vy: number) => cruise(vx, vy, 2).at(-1)!.hipYaw;
    expect(settled(9, 0)).toBeCloseTo(0, 6);
    expect(settled(0, 9)).toBeCloseTo(0, 6);
    expect(settled(-9, 0)).toBeCloseTo(0, 6);
    // Forward and to the strafe-positive side: the pelvis follows the travel.
    expect(settled(9, 9)).toBeGreaterThan(0.3);
    // Backing away the same way, it turns the other way, so the hips still
    // face along the line being travelled.
    expect(settled(-9, 9)).toBeLessThan(-0.3);
  });

  it('treats a respawn as a respawn, not as a sprint', () => {
    const gait = createGait();
    const input: GaitInput = { x: 0, y: 0, yaw: 0, alive: true, grounded: true, ...BODY };
    stepGait(gait, input, DT);
    input.x += TELEPORT_SPEED * DT * 2;
    const out = stepGait(gait, input, DT);
    expect(out.speed).toBe(0);
    expect(out.weight).toBe(0);
    expect(Math.abs(out.feet[0].x - input.x)).toBeLessThan(BODY.hipWidth);
  });
});

function row(over: Partial<PlayerRow> = {}): PlayerRow {
  return {
    id: 'p1',
    name: 'Operator',
    team: 0,
    x: 40,
    y: 37.5,
    z: 3,
    yaw: 0,
    pitch: 0,
    ground: true,
    stale: false,
    rtt: 20,
    hp: 100,
    alive: true,
    weapon: 2,
    kills: 0,
    deaths: 0,
    bot: false,
    crouch: 0,
    ...over,
  };
}

/** One operator in a scene of its own, placed the way `AvatarPool.sync` does. */
function stage(file: string) {
  const asset = loadOperatorGlb(file);
  const model = new CharacterModel(THREE, asset, 0, 'Operator');
  const animator = new CharacterAnimator(THREE, model, asset);
  const bone = (name: string) => {
    const found = model.bones.get(name);
    if (!found) throw new Error(`${file}: no ${name} bone`);
    return found;
  };
  // Bind pose, before anything plays: where an ankle sits with the foot flat.
  model.rootGroup.updateMatrixWorld(true);
  const ankleRest = bone('LeftFoot').getWorldPosition(new THREE.Vector3()).y;
  const frame = (r: PlayerRow, dt = DT) => {
    model.rootGroup.position.set(r.x, r.z, r.y);
    model.rootGroup.rotation.y = avatarRotationY(r.yaw);
    animator.update(dt, r);
    model.rootGroup.updateMatrixWorld(true);
  };
  return { model, animator, bone, frame, ankleRest };
}

const RIGS = ['hassault-operator.glb', 'hassault-operator-t.glb'];

describe.each(RIGS)('%s on its feet', (file) => {
  it.each([
    ['walking', 4, 0.4],
    ['running', RUN_SPEED, 0.12],
  ])('slides under 2%% of the ground it covers, %s', (_name, speed, share) => {
    for (let dir = 0; dir < 8; dir += 1) {
      const { bone, frame, ankleRest } = stage(file);
      const yaw = 0.7;
      const angle = yaw + (dir * Math.PI) / 4;
      const r = row({ yaw });
      const feet = [bone('LeftFoot'), bone('RightFoot')];
      const last = feet.map(() => new THREE.Vector3());
      const down = [false, false];
      const at = new THREE.Vector3();
      let slid = 0;
      let travelled = 0;
      let grounded = 0;
      const frames = 240;
      for (let i = 0; i < frames; i += 1) {
        r.x += speed * Math.cos(angle) * DT;
        r.y += speed * Math.sin(angle) * DT;
        frame(r);
        const settled = i >= 60;
        if (settled) travelled += speed * DT;
        feet.forEach((foot, f) => {
          foot.getWorldPosition(at);
          // On the ground is where the ankle is as low as a flat foot puts it.
          const isDown = at.y - r.z < ankleRest + 0.03;
          if (settled && isDown && down[f]) {
            slid += Math.hypot(at.x - last[f].x, at.z - last[f].z);
            grounded += 1;
          }
          down[f] = isDown;
          last[f].copy(at);
        });
      }
      // A leg that cannot reach its target never reads as down, and would pass
      // the slide test by never being measured.
      expect(
        grounded / (2 * (frames - 60)),
        `direction ${dir}: time on the ground`,
      ).toBeGreaterThan(share);
      expect(slid / travelled, `direction ${dir}`).toBeLessThan(0.02);
    }
  });
});

describe.each(RIGS)('%s aiming', (file) => {
  /** Degrees between a bone's axis and the look direction. */
  const off = (bone: THREE.Object3D, axis: THREE.Vector3, r: PlayerRow) => {
    const pitch = r.pitch ?? 0;
    const look = new THREE.Vector3(
      Math.cos(r.yaw) * Math.cos(pitch),
      Math.sin(pitch),
      Math.sin(r.yaw) * Math.cos(pitch),
    );
    const pointing = axis.clone().applyQuaternion(bone.getWorldQuaternion(new THREE.Quaternion()));
    return THREE.MathUtils.radToDeg(pointing.angleTo(look));
  };

  const STATES: [string, Partial<PlayerRow>, [number, number], boolean][] = [
    ['standing', {}, [0, 0], false],
    ['running forward', {}, [RUN_SPEED, 0], false],
    ['strafing', {}, [0, 9], false],
    ['backing up', {}, [-9, 0], false],
    ['on a diagonal', {}, [9, -9], false],
    ['crouched', { crouch: 1 }, [0, 0], false],
    ['crouch-walking', { crouch: 1 }, [5, 0], false],
    ['in the air', { ground: false }, [12, 0], false],
    ['firing on the move', {}, [RUN_SPEED, 0], true],
  ];

  it.each(STATES)('points the rifle and the face down the look, %s', (_name, over, v, fire) => {
    for (const pitch of [-1, 0, 1]) {
      for (const yaw of [0, 2.3]) {
        const { model, animator, bone, frame } = stage(file);
        const r = row({ ...over, yaw, pitch });
        // Bind pose: the face is model +Z, so this is the head's own forward.
        const face = new THREE.Vector3(0, 0, 1).applyQuaternion(
          bone('Head').getWorldQuaternion(new THREE.Quaternion()).invert(),
        );
        const side = new THREE.Vector3(1, 0, 0).applyQuaternion(
          bone('Head').getWorldQuaternion(new THREE.Quaternion()).invert(),
        );
        for (let i = 0; i < 50; i += 1) {
          r.x += (v[0] * Math.cos(yaw) - v[1] * Math.sin(yaw)) * DT;
          r.y += (v[0] * Math.sin(yaw) + v[1] * Math.cos(yaw)) * DT;
          if (fire && i === 45) animator.triggerRecoil();
          frame(r);
          // Every frame, not only the settled one: a crossfade or a stride is
          // exactly when the old fixed lean drifted off.
          expect(off(bone('RightHand'), new THREE.Vector3(0, 1, 0), r)).toBeLessThan(3);
          expect(off(bone('Head'), face, r)).toBeLessThan(3);
          // And level: the height of the ear-to-ear axis, zero on a head that
          // is not cocked to one side.
          const ears = side
            .clone()
            .applyQuaternion(bone('Head').getWorldQuaternion(new THREE.Quaternion()));
          expect(Math.abs(ears.y)).toBeLessThan(0.05);
        }
        animator.dispose();
        model.dispose();
      }
    }
  });

  it('lets a reload take the rifle off the line while the head stays on it', () => {
    const { model, animator, bone, frame } = stage(file);
    const r = row({ yaw: 1.1, pitch: 0.4 });
    const face = new THREE.Vector3(0, 0, 1).applyQuaternion(
      bone('Head').getWorldQuaternion(new THREE.Quaternion()).invert(),
    );
    frame(r);
    animator.triggerReload();
    let most = 0;
    for (let i = 0; i < 60; i += 1) {
      frame(r);
      most = Math.max(most, off(bone('RightHand'), new THREE.Vector3(0, 1, 0), r));
      expect(off(bone('Head'), face, r)).toBeLessThan(3);
    }
    expect(most).toBeGreaterThan(10);
    animator.dispose();
    model.dispose();
  });

  it('leaves a dead body to its death clip', () => {
    // Looking up as they died is not a reason for a corpse to crane its neck.
    const poses = [0, 1].map((pitch) => {
      const { model, animator, bone, frame } = stage(file);
      const r = row({ alive: false, pitch });
      for (let i = 0; i < 30; i += 1) frame(r);
      const pose = ['Head', 'Spine2', 'RightHand', 'LeftFoot'].map((name) =>
        bone(name).getWorldQuaternion(new THREE.Quaternion()),
      );
      animator.dispose();
      model.dispose();
      return pose;
    });
    // `angleTo` goes through an arccosine, which is only good to ~1e-4 near 0.
    poses[0].forEach((q, i) => expect(q.angleTo(poses[1][i])).toBeLessThan(1e-3));
  });
});
