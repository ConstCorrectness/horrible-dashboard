"""The script that runs inside a training project's venv.

This module holds a **template**, not code that executes here. `runner_project`
writes it into the project directory and runs it with the project's own python,
because that is where `datasets` and `evaluate` live — they pull torch-class
dependencies that must never become core deps of the backend.

Three properties the template has to have, and they pull against each other:

1. **It must be readable.** It lands in your project as `evals/run_benchmark.py`
   and is meant to be opened, understood and edited. That is half the point of
   running HF benchmarks *in the dashboard* rather than shelling out — the file is
   how you learn what the libraries do.
2. **It must have no dependency it does not need.** The model is called over plain
   `urllib` rather than `httpx` or the `openai` client, so a benchmark that needs
   nothing but `datasets` installs nothing but `datasets`. `evaluate` is imported
   lazily and only for metrics the harness does not implement itself.
3. **It must be machine-readable on the way out.** It prints a single JSON object
   on a sentinel line. Parsing a score out of prose is how a harness starts
   reporting numbers nobody can reproduce.

It is a string template rather than a file copied verbatim so the job description
is baked in at write time; `{{` and `}}` are literal braces after `.format()`.
"""

from __future__ import annotations

import inspect
import json
import re
from typing import Any

#: The line the runner looks for. Everything else on stdout is progress the user
#: sees streamed into the pane.
RESULT_SENTINEL = "__HORRIBLE_EVAL_RESULT__"

# --- scoring, defined once and used twice -----------------------------------
#
# These two are real functions here AND inlined into the generated script via
# `inspect.getsource`. One definition, because the alternative is a copy in the
# template and a copy for the preview endpoint that silently disagree — and the
# thing they disagree about would be *what the score means*, which is the one
# number this whole module exists to produce.


def extract(text, pattern):
    """Pull the gradeable answer out with a regex, or leave it alone.

    Most reasoning datasets store the worked solution in the answer column and
    mark the final answer with a separator (GSM8K uses `#### N`). Grading the
    column as-is asks whether the model reproduced the dataset's prose, which
    scores zero for a reason that has nothing to do with the model.

    A pattern that does not match leaves the value untouched rather than
    returning empty: degrading to "compare the whole thing" is recoverable and
    visible in the samples, whereas silently comparing against "" scores zero and
    looks like a model failure.
    """
    if not pattern:
        return text
    found = re.search(pattern, str(text), re.S)
    if not found:
        return text
    return found.group(1) if found.groups() else found.group(0)


def normalise(text):
    """Lowercase, collapse whitespace, drop trailing punctuation and separators.

    Applied to both sides before comparing. Without it `exact_match` measures
    formatting; with it, it measures the answer. Thousands separators and a
    trailing currency symbol go too, because `$1,000` and `1000` are the same
    answer and no dataset agrees on which to store.
    """
    text = re.sub(r"\s+", " ", str(text)).strip().lower()
    text = text.strip("$ ").rstrip(".!,")
    return text.replace(",", "")


TEMPLATE = '''"""Run one Hugging Face benchmark against a served model.

Generated by the dashboard's evals module, and yours to edit — it is an ordinary
script in your project, run with your project's python. Re-running the benchmark
from the dashboard regenerates it, so save a copy under a different name if you
change it and want to keep the change.

What it does:

  1. loads `{dataset}` with `datasets`
  2. renders each row into a prompt with `input_template`
  3. asks the model, over an OpenAI-compatible /v1/chat/completions endpoint
  4. scores the answers
  5. prints one JSON object the dashboard reads back

The model is called with plain `urllib` on purpose: a benchmark that needs nothing
but `datasets` should install nothing but `datasets`.
"""

import json
import re
import sys
import urllib.error
import urllib.request

JOB = {job}
SENTINEL = "{sentinel}"


def log(message):
    """Progress. The dashboard streams these into the pane as they arrive, so
    flush — a buffered run looks identical to a hung one."""
    print(message, flush=True)


def ask(prompt):
    """One chat completion. Returns the assistant text, or raises."""
    messages = []
    if JOB["system"]:
        messages.append({{"role": "system", "content": JOB["system"]}})
    messages.append({{"role": "user", "content": prompt}})

    body = json.dumps(
        {{
            "model": JOB["model"],
            "messages": messages,
            # Zero, always: a benchmark is a measurement, and a score that moves
            # between identical runs cannot tell a fine-tune from sampling noise.
            "temperature": 0,
            "stream": False,
        }}
    ).encode()
    request = urllib.request.Request(
        JOB["endpoint"].rstrip("/") + "/v1/chat/completions",
        data=body,
        headers={{"Content-Type": "application/json"}},
    )
    with urllib.request.urlopen(request, timeout=JOB["timeout"]) as response:
        payload = json.loads(response.read())
    return payload["choices"][0]["message"]["content"] or ""


{scoring}


def score_one(prediction, reference):
    """One row's score, by the job's metric.

    `exact_match` and `contains` are implemented here so the common case needs no
    extra dependency. Anything else is handed to `evaluate`, imported lazily so a
    missing install fails with a useful message rather than at import time.
    """
    metric = JOB["metric"]
    if metric == "exact_match":
        return 1.0 if normalise(prediction) == normalise(reference) else 0.0
    if metric == "contains":
        return 1.0 if normalise(reference) in normalise(prediction) else 0.0

    import evaluate  # noqa: PLC0415 - lazy on purpose, see the docstring

    scorer = evaluate.load(metric)
    result = scorer.compute(predictions=[prediction], references=[reference])
    # `evaluate` metrics return a dict whose useful key is named after the metric,
    # or something close to it. Take the metric's own key when it is there and the
    # first numeric value otherwise, rather than guessing at a name.
    if metric in result:
        return float(result[metric])
    for value in result.values():
        if isinstance(value, (int, float)):
            return float(value)
    raise RuntimeError("metric " + metric + " returned no numeric value: " + repr(result))


def main():
    from datasets import load_dataset

    log("loading " + JOB["dataset"] + (" [" + JOB["config"] + "]" if JOB["config"] else ""))
    args = [JOB["dataset"]] + ([JOB["config"]] if JOB["config"] else [])
    rows = load_dataset(*args, split=JOB["split"])

    limit = min(JOB["limit"], len(rows))
    log("running " + str(limit) + " rows against " + JOB["model"])

    scores = []
    samples = []
    errors = 0
    for index in range(limit):
        row = rows[index]
        try:
            prompt = JOB["input_template"].format(**row)
        except KeyError as exc:
            # A template naming a column the dataset does not have is a mistake in
            # the case, and it will be a mistake on every row — so stop rather than
            # produce a run of identical failures.
            print(SENTINEL + json.dumps({{
                "error": "input_template names a column this dataset lacks: "
                         + str(exc) + ". Columns are: " + ", ".join(rows.column_names)
            }}), flush=True)
            return 1

        reference = row.get(JOB["target_column"])
        if reference is None:
            print(SENTINEL + json.dumps({{
                "error": "target_column " + repr(JOB["target_column"])
                         + " is not in this dataset. Columns are: "
                         + ", ".join(rows.column_names)
            }}), flush=True)
            return 1

        raw = ""
        try:
            raw = ask(prompt)
            prediction = extract(raw, JOB["prediction_regex"])
            value = score_one(prediction, extract(reference, JOB["target_regex"]))
        except urllib.error.URLError as exc:
            # A dead endpoint is worth failing the whole job over; a per-row error
            # would report it as a model that got everything wrong.
            print(SENTINEL + json.dumps({{
                "error": "could not reach the model at " + JOB["endpoint"] + ": " + str(exc)
            }}), flush=True)
            return 1
        except Exception as exc:  # one bad row must not end the run
            errors += 1
            value = 0.0
            prediction = "<error: " + str(exc) + ">"

        scores.append(value)
        if len(samples) < 5:
            # Both the raw reply and what was actually compared: a regex that
            # matched the wrong thing is otherwise invisible, and that is the
            # single most likely reason for a surprising zero.
            samples.append({{
                "prompt": prompt[:300],
                "raw": str(raw)[:300],
                "prediction": str(prediction)[:200],
                "reference": str(extract(reference, JOB["target_regex"]))[:200],
                "score": value,
            }})
        if (index + 1) % 10 == 0 or index + 1 == limit:
            running = sum(scores) / len(scores)
            log("  " + str(index + 1) + "/" + str(limit) + "  score " + format(running, ".3f"))

    result = {{
        "score": (sum(scores) / len(scores)) if scores else 0.0,
        "rows": len(scores),
        "errors": errors,
        "metric": JOB["metric"],
        "samples": samples,
    }}
    print(SENTINEL + json.dumps(result), flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
'''


def render(job: dict[str, Any]) -> str:
    """The script for one benchmark job.

    `job` is embedded as a Python literal via `json.dumps` rather than interpolated
    field by field: a dataset id or a template with a quote in it would otherwise
    end the string and produce a script that fails to parse, which is a class of
    bug worth designing out rather than escaping around.
    """
    return TEMPLATE.format(
        job=json.dumps(job, indent=4),
        sentinel=RESULT_SENTINEL,
        dataset=job.get("dataset", ""),
        # Inlined from this module rather than duplicated in the template, so the
        # preview in the case editor and the script that produces the real score
        # can never drift.
        scoring=(
            inspect.getsource(extract).rstrip()
            + "\n\n\n"
            + inspect.getsource(normalise).rstrip()
        ),
    )
